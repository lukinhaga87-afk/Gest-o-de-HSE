export function getActivityTemplateByCode(codigo: string): ActivityProfileTemplateSeed | undefined {
  const normalized = codigo.trim().toUpperCase();
  return INITIAL_ACTIVITY_TEMPLATES.find((tpl) => tpl.codigo === normalized);
}

/**
 * Converte um template inicial em payload pronto para persistência na coleção `activityProfiles`.
 * O registro gerado passa a ser 100% editável pelo Admin EHS no Firestore.
 */
export function buildActivityProfilePayloadFromTemplate(
  template: ActivityProfileTemplateSeed,
  adminActor: { id: string; nome: string },
  timestampIso = new Date().toISOString()
): Omit<ActivityProfile, 'id'> {
  return {
    codigo: template.codigo,
    nome: template.nome,
    descricao: template.descricao,
    nivelRisco: template.nivelRisco,
    riscosAssociados: [...template.riscosAssociados],
    normasAplicaveis: [...template.normasAplicaveis],
    exigeAPR: template.exigeAPR,
    exigePT: template.exigePT,
    exigeLOTO: template.exigeLOTO,
    exigePET: Boolean(template.exigePET),
    templateOrigem: template.templateKey,
    ativo: true,
    criadoPorId: adminActor.id,
    criadoPorNome: adminActor.nome,
    atualizadoPorId: adminActor.id,
    atualizadoPorNome: adminActor.nome,
    createdAt: timestampIso,
    updatedAt: timestampIso,
  };
}

/**
 * Converte os requisitos de um template inicial em payloads prontos para persistência
 * na coleção `activityDocumentRequirements`, vinculados ao `activityId` criado.
 */
export function buildRequirementsPayloadFromTemplate(
  template: ActivityProfileTemplateSeed,
  activityId: string,
  adminActor: { id: string; nome: string },
  timestampIso = new Date().toISOString()
): Omit<ActivityDocumentRequirement, 'id'>[] {
  return template.requisitosPadrao.map((req) => ({
    activityId,
    activityCodigo: template.codigo,
    nomeExibicao: req.nomeExibicao,
    descricao: req.descricao,
    documentoCodigoCanonico: req.documentoCodigoCanonico,
    palavrasChaveMatch: [...req.palavrasChaveMatch],
    escopo: req.escopo,
    origemColecao: req.origemColecao,
    funcoesAplicaveis: [...req.funcoesAplicaveis],
    ...(req.exigeAptoASO !== undefined ? { exigeAptoASO: req.exigeAptoASO } : {}),
    ...(req.aptidaoEspecifica ? { aptidaoEspecifica: req.aptidaoEspecifica } : {}),
    ...(req.validadePadraoMeses !== undefined ? { validadePadraoMeses: req.validadePadraoMeses } : {}),
    obrigatorioParaLiberacao: req.obrigatorioParaLiberacao,
    baseLegal: req.baseLegal,
    ordemExibicao: req.ordemExibicao,
    templateOrigem: req.templateKey,
    ativo: true,
    criadoPorId: adminActor.id,
    criadoPorNome: adminActor.nome,
    atualizadoPorId: adminActor.id,
    atualizadoPorNome: adminActor.nome,
    createdAt: timestampIso,
    updatedAt: timestampIso,
  }));
}
